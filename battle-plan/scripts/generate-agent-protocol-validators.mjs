import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, '..');
const schemaRoot = path.resolve(appRoot, '../docs/agent-protocol/v2/schemas');
const outputPath = path.resolve(appRoot, 'src/services/agentProtocol/generatedValidators.js');
const declarationPath = path.resolve(appRoot, 'src/services/agentProtocol/generatedValidators.d.ts');
const publicOutputPath = path.resolve(appRoot, '../docs/agent-protocol/v2/generated-validators.mjs');
const manifestPath = path.resolve(appRoot, '../docs/agent-protocol/v2/ARTIFACT_MANIFEST.json');
const ARTIFACT_MANIFEST_DOMAIN = 'BattlePlan-Hermes/artifact-manifest/v1\0';
const schemaFiles = (await readdir(schemaRoot))
    .filter((file) => file.endsWith('.schema.json'))
    .sort();

const exportsByType = {
    hello: 'validateHello',
    capability: 'validateCapability',
    command: 'validateCommand',
    result: 'validateResult',
    'event-batch': 'validateEventBatch',
    snapshot: 'validateSnapshot',
    proposal: 'validateProposal',
    response: 'validateResponse',
    'drive-receipt': 'validateDriveReceipt',
};

function canonicalize(value) {
    if (value === null || typeof value !== 'object') return JSON.stringify(value);
    if (Array.isArray(value)) return `[${value.map(canonicalize).join(',')}]`;
    return `{${Object.keys(value).sort().map((key) => `${JSON.stringify(key)}:${canonicalize(value[key])}`).join(',')}}`;
}

const schemaSources = await Promise.all(schemaFiles.map(async (file) => ({
    file,
    source: await readFile(path.join(schemaRoot, file)),
})));
const manifestMaterial = {
    format: 'battleplan-hermes-contract-manifest/v1',
    artifact_id: 'battleplan-hermes-protocol',
    version: '2.0.0',
    schemas: schemaSources.map(({ file, source }) => ({
        path: `schemas/${file}`,
        bytes: source.byteLength,
        sha256: `sha256:${createHash('sha256').update(source).digest('hex')}`,
    })),
};
const manifest = {
    ...manifestMaterial,
    artifact_sha256: `sha256:${createHash('sha256').update(`${ARTIFACT_MANIFEST_DOMAIN}${canonicalize(manifestMaterial)}`, 'utf8').digest('hex')}`,
};
const generatedManifest = `${JSON.stringify(manifest, null, 2)}\n`;

const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    // Required fields are intentionally composed across allOf/$ref boundaries.
    // Ajv cannot statically see those sibling properties, while runtime validation remains strict.
    strictRequired: false,
    validateFormats: true,
    code: { esm: true, source: true, optimize: true },
});
addFormats(ajv);
// Override function-backed temporal formats with serializable RFC 3339 forms
// so standalone ESM never emits CommonJS `require()` into the Vite bundle.
// The date branch enforces Gregorian month lengths and leap-year rules; the
// time branch accepts numeric offsets. Protocol v2 deliberately rejects `:60`
// because JavaScript Date cannot safely enforce or compare leap seconds.
const fullDate = '(?:(?:[0-9]{2}(?:0[48]|[2468][048]|[13579][26])|(?:[02468][048]|[13579][26])00)-02-29|[0-9]{4}-(?:(?:0[13578]|1[02])-(?:0[1-9]|[12][0-9]|3[01])|(?:0[469]|11)-(?:0[1-9]|[12][0-9]|30)|02-(?:0[1-9]|1[0-9]|2[0-8])))';
const fullTime = 'T(?:[01][0-9]|2[0-3]):[0-5][0-9]:[0-5][0-9](?:\\.[0-9]+)?(?:Z|[+-](?:[01][0-9]|2[0-3]):[0-5][0-9])';
ajv.addFormat('date', new RegExp(`^${fullDate}$`, 'u'));
ajv.addFormat('date-time', new RegExp(`^${fullDate}${fullTime}$`, 'u'));

for (const { source } of schemaSources) {
    const schema = JSON.parse(source.toString('utf8'));
    ajv.addSchema(schema);
}

const validatorRefs = Object.fromEntries(Object.entries(exportsByType).map(([type, exportName]) => [
    exportName,
    `https://battleplan.app/agent-protocol/v2/schemas/${type}.schema.json`,
]));
const standalone = standaloneCode(ajv, validatorRefs)
    .replaceAll('require("ajv/dist/runtime/equal").default', 'protocolDeepEqual')
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'protocolUnicodeLength');
const runtimeHelpers = `function protocolUnicodeLength(value) { return [...value].length; }\nfunction protocolDeepEqual(left, right) {\n    if (left === right) return true;\n    if (!left || !right || typeof left !== 'object' || typeof right !== 'object') return false;\n    if (Array.isArray(left) !== Array.isArray(right)) return false;\n    const leftKeys = Object.keys(left);\n    const rightKeys = Object.keys(right);\n    return leftKeys.length === rightKeys.length\n        && leftKeys.every((key) => Object.hasOwn(right, key) && protocolDeepEqual(left[key], right[key]));\n}\n`;
const generated = `// Generated by scripts/generate-agent-protocol-validators.mjs. Do not edit.\n${runtimeHelpers}${standalone}`;
const declaration = `// Generated declaration for CSP-safe standalone validators.\nimport type { ErrorObject } from 'ajv';\nexport interface ProtocolStandaloneValidator {\n    (data: unknown): boolean;\n    errors?: ErrorObject[] | null;\n}\n${Object.values(exportsByType).map((name) => `export const ${name}: ProtocolStandaloneValidator;`).join('\n')}\n`;

if (process.argv.includes('--check')) {
    const [currentGenerated, currentDeclaration, currentPublicGenerated, currentManifest] = await Promise.all([
        readFile(outputPath, 'utf8').catch(() => ''),
        readFile(declarationPath, 'utf8').catch(() => ''),
        readFile(publicOutputPath, 'utf8').catch(() => ''),
        readFile(manifestPath, 'utf8').catch(() => ''),
    ]);
    if (
        currentGenerated !== generated
        || currentDeclaration !== declaration
        || currentPublicGenerated !== generated
        || currentManifest !== generatedManifest
    ) {
        console.error('Agent protocol validators or ARTIFACT_MANIFEST.json are stale. Run npm run agent-protocol:generate.');
        process.exitCode = 1;
    }
} else {
    await Promise.all([
        writeFile(outputPath, generated, 'utf8'),
        writeFile(declarationPath, declaration, 'utf8'),
        writeFile(publicOutputPath, generated, 'utf8'),
        writeFile(manifestPath, generatedManifest, 'utf8'),
    ]);
    console.log(`Generated ${Object.keys(exportsByType).length} CSP-safe protocol validators.`);
}
