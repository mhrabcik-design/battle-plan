import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import addFormats from 'ajv-formats';
import standaloneCode from 'ajv/dist/standalone/index.js';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(scriptDir, '..');
const schemaRoot = path.resolve(appRoot, '../docs/agent-protocol/v2/schemas');
const outputPath = path.resolve(appRoot, 'src/services/agentProtocol/generatedValidators.js');
const declarationPath = path.resolve(appRoot, 'src/services/agentProtocol/generatedValidators.d.ts');
const publicOutputPath = path.resolve(appRoot, '../docs/agent-protocol/v2/generated-validators.mjs');

const schemaFiles = [
    'envelope.schema.json',
    'signature.schema.json',
    'revision.schema.json',
    'hello.schema.json',
    'command.schema.json',
    'result.schema.json',
    'event-batch.schema.json',
    'snapshot.schema.json',
    'proposal.schema.json',
    'response.schema.json',
    'capability.schema.json',
];

const exportsByType = {
    hello: 'validateHello',
    capability: 'validateCapability',
    command: 'validateCommand',
    result: 'validateResult',
    'event-batch': 'validateEventBatch',
    snapshot: 'validateSnapshot',
    proposal: 'validateProposal',
    response: 'validateResponse',
};

const ajv = new Ajv2020({
    allErrors: true,
    strict: true,
    // Required fields are intentionally composed across allOf/$ref boundaries.
    // Ajv cannot statically see those sibling properties, while runtime validation remains strict.
    strictRequired: false,
    validateFormats: true,
    code: { esm: true, source: true, optimize: true },
});
addFormats(ajv);
// Override function-backed temporal formats with serializable strict forms so
// standalone ESM never emits CommonJS `require()` into the Vite bundle.
ajv.addFormat('date', /^\d{4}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01])$/u);
ajv.addFormat('date-time', /^\d{4}-(?:0[1-9]|1[0-2])-(?:0[1-9]|[12]\d|3[01])T(?:[01]\d|2[0-3]):[0-5]\d:[0-5]\d(?:\.\d{1,9})?Z$/u);

for (const file of schemaFiles) {
    const schema = JSON.parse(await readFile(path.join(schemaRoot, file), 'utf8'));
    ajv.addSchema(schema);
}

const validatorRefs = Object.fromEntries(Object.entries(exportsByType).map(([type, exportName]) => [
    exportName,
    `https://battleplan.app/agent-protocol/v2/schemas/${type}.schema.json`,
]));
const standalone = standaloneCode(ajv, validatorRefs)
    .replaceAll('require("ajv/dist/runtime/equal").default', 'protocolDeepEqual')
    .replaceAll('require("ajv/dist/runtime/ucs2length").default', 'protocolUnicodeLength');
const runtimeHelpers = `function protocolUnicodeLength(value) { return [...value].length; }\nfunction protocolDeepEqual(left, right) {\n    if (left === right) return true;\n    if (!left || !right || typeof left !== 'object' || typeof right !== 'object') return false;\n    if (Array.isArray(left) !== Array.isArray(right)) return false;\n    const leftKeys = Object.keys(left);\n    const rightKeys = Object.keys(right);\n    return leftKeys.length === rightKeys.length\n        && leftKeys.every((key) => Object.hasOwn(right, key) && protocolDeepEqual(left[key], right[key]));\n}\n`;
const generated = `// Generated by scripts/generate-agent-protocol-validators.mjs. Do not edit.\n${runtimeHelpers}${standalone}`;
const declaration = `// Generated declaration for CSP-safe standalone validators.\nimport type { ErrorObject } from 'ajv';\nexport interface ProtocolStandaloneValidator {\n    (data: unknown): boolean;\n    errors?: ErrorObject[] | null;\n}\n${Object.values(exportsByType).map((name) => `export const ${name}: ProtocolStandaloneValidator;`).join('\n')}\n`;

if (process.argv.includes('--check')) {
    const [currentGenerated, currentDeclaration, currentPublicGenerated] = await Promise.all([
        readFile(outputPath, 'utf8').catch(() => ''),
        readFile(declarationPath, 'utf8').catch(() => ''),
        readFile(publicOutputPath, 'utf8').catch(() => ''),
    ]);
    if (currentGenerated !== generated || currentDeclaration !== declaration || currentPublicGenerated !== generated) {
        console.error('Agent protocol validators are stale. Run npm run agent-protocol:generate.');
        process.exitCode = 1;
    }
} else {
    await Promise.all([
        writeFile(outputPath, generated, 'utf8'),
        writeFile(declarationPath, declaration, 'utf8'),
        writeFile(publicOutputPath, generated, 'utf8'),
    ]);
    console.log(`Generated ${Object.keys(exportsByType).length} CSP-safe protocol validators.`);
}
